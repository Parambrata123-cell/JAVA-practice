// declared a class named Even_Odd
public class Even_Odd {
    public static void main(String[] args) {
        // using For Loop
        for (int i = 1; i <= 5; i++) {
            if (i % 2 == 0) {
                System.out.println(i + " is even");
            } else {
                System.out.println(i + " is odd");
            }
        }
    }
}
